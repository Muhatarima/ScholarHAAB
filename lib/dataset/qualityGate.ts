/**
 * Dataset quality score 0–100. Production RAG rejects score < 70.
 * Checks: license, relevance, subject mapping, board compatibility, dedup, low-quality/generated content.
 */

export type DatasetQualityMeta = {
  name: string
  license: string
  relevance: boolean
  subjectMapped: boolean
  boardSupported: boolean
  hasDuplicates: boolean
  /** AI-slop / empty / template spam */
  lowQualityOrGenerated?: boolean
  chapter?: string | null
  topic?: string | null
  level?: string | null
  board?: string | null
  subject?: string | null
}

export type QualityResult = {
  name: string
  score: number
  licenseOk: boolean
  relevanceOk: boolean
  subjectOk: boolean
  boardOk: boolean
  dedupedOk: boolean
  contentQualityOk: boolean
  passed: boolean
  tags: {
    board: string | null
    level: string | null
    subject: string | null
    chapter: string | null
    topic: string | null
  }
  details: string
}

const PERMITTED_LICENSE_TERMS = [
  'cc0',
  'cc-by',
  'cc by',
  'creative commons',
  'mit',
  'apache',
  'public domain',
  'user_provided',
  'user provided',
  'permitted',
  'open government',
  'cambridge',
  'edexcel',
  'exam board',
]

const GENERATED_CONTENT_PATTERNS = [
  /\bas an ai language model\b/i,
  /\bi cannot provide\b/i,
  /\blorem ipsum\b/i,
  /\bplaceholder\b/i,
  /\b\[insert\b/i,
  /\btodo:\s*fill\b/i,
  /\bgenerated by chatgpt\b/i,
]

export const PRODUCTION_QUALITY_THRESHOLD = 70

export function isPermittedLicense(license: string) {
  const licenseLower = String(license || '').toLowerCase()
  return PERMITTED_LICENSE_TERMS.some((term) => licenseLower.includes(term))
}

export function looksLowQualityOrGenerated(text: string) {
  const compact = text.replace(/\s+/g, ' ').trim()
  if (compact.length < 20) return true
  if (GENERATED_CONTENT_PATTERNS.some((p) => p.test(compact))) return true
  const alpha = (compact.match(/[a-z]/gi) ?? []).length
  if (alpha / compact.length < 0.35) return true
  return false
}

export function evaluateDatasetQuality(meta: DatasetQualityMeta, sampleText = ''): QualityResult {
  let score = 0

  const licenseOk = isPermittedLicense(meta.license)
  if (licenseOk) score += 25
  if (meta.relevance) score += 20
  if (meta.subjectMapped) score += 20
  if (meta.boardSupported) score += 15
  if (!meta.hasDuplicates) score += 10

  const contentQualityOk = !meta.lowQualityOrGenerated && (!sampleText || !looksLowQualityOrGenerated(sampleText))
  if (contentQualityOk) score += 10

  const passed = score >= PRODUCTION_QUALITY_THRESHOLD && licenseOk && contentQualityOk

  return {
    name: meta.name,
    score,
    licenseOk,
    relevanceOk: meta.relevance,
    subjectOk: meta.subjectMapped,
    boardOk: meta.boardSupported,
    dedupedOk: !meta.hasDuplicates,
    contentQualityOk,
    passed,
    tags: {
      board: meta.board ?? null,
      level: meta.level ?? null,
      subject: meta.subject ?? null,
      chapter: meta.chapter ?? null,
      topic: meta.topic ?? null,
    },
    details: `Score ${score}/100. License: ${licenseOk ? 'ok' : 'rejected'}. Content: ${contentQualityOk ? 'ok' : 'low-quality/generated'}.`,
  }
}

export function assertProductionQuality(meta: DatasetQualityMeta, sampleText = '') {
  const result = evaluateDatasetQuality(meta, sampleText)
  if (!result.passed) {
    throw new Error(`Dataset rejected for production RAG: ${result.name} — ${result.details}`)
  }
  return result
}
